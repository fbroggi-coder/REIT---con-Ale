-- Historial de valor de cuotaparte (VCP) por fondo
-- Correr UNA vez en Supabase → SQL Editor.
-- Después, cada PDF que se carga en la web agrega/actualiza la fila del día.
-- ═══════════════════════════════════════════════════════════════════

create table if not exists public.vcp_historial (
  fund_id      text        not null,
  fecha        date        not null,
  clase        text        not null default 'A',
  vcp          numeric     not null,          -- valor por cuotaparte (por unidad)
  pn           numeric,                       -- patrimonio neto de la clase (si se conoce)
  cuotapartes  numeric,
  fuente       text        default 'pdf',     -- 'pdf' | 'excel'
  created_at   timestamptz default now(),
  primary key (fund_id, fecha, clase)
);

-- Mismo esquema de acceso que el resto de las tablas de la web (clave anon).
-- OJO: esto permite escribir a cualquiera con la clave anon, igual que holdings/funds.
alter table public.vcp_historial enable row level security;
drop policy if exists "vcp_historial lectura"  on public.vcp_historial;
drop policy if exists "vcp_historial escritura" on public.vcp_historial;
drop policy if exists "vcp_historial update"    on public.vcp_historial;
create policy "vcp_historial lectura"   on public.vcp_historial for select using (true);
create policy "vcp_historial escritura" on public.vcp_historial for insert with check (true);
create policy "vcp_historial update"    on public.vcp_historial for update using (true) with check (true);

